"""Generate exact rational panel certificates; Lean checks every rounded cell."""
from fractions import Fraction as F
from pathlib import Path
import argparse
import json
Z = [F(n, 10**6) for n in [22266,21591,20159,18016,15756,12894,9961,7682,7139]]
def lower(x):
    v = (x-1)/(x+1)
    return 2*sum(v**k/k for k in [1,3,5,7])
def cell(a,b,A,B):
    return (b-a)*(A+B)/(a+b)-(B-A)*(b-a)**2/(3*(a+b)**2)
def rounded(v):
    return v.numerator*10**12//v.denominator

def generate(idx):
    S = 2+F(idx,10)
    rows = []
    for k in range(9):
        a = max(F(1) if k==0 else F(21+k,10), S-2)
        b = F(22+k,10)
        xs = [a+(b-a)*F(j,8) for j in range(9)]
        rows.append([rounded(Z[k]*cell(l,r,lower((l+1)/(S-1)),lower((r+1)/(S-1))))
                     if a<b else 0 for l,r in zip(xs,xs[1:])])
    sigma = rounded(F(1105570288,10**12)*lower(4/(S-1)))
    target = (sigma+sum(map(sum,rows)))//100
    s = f'''import WR2XiSourceNodeCertificate

/-! Generated by generate-source-node-certificate.py; all bounds checked by norm_num. -/
noncomputable section
namespace WuPaper.R2Xi.SourceRational.Node{idx}
open NodeExtension WuTarget.W02
open scoped Classical

'''
    for k,row in enumerate(rows):
        s += f'def q{k} : Fin 8 → ℝ := !['+','.join(f'{n}/1000000000000' for n in row)+']\n\n'
        s += f'''theorem q{k}_paid (j : Fin 8) : q{k} j ≤ panelTerm (rNode {idx}) ⟨{k}, by omega⟩ j := by
  fin_cases j <;> norm_num [q{k}, panelTerm, tailLeft, upperLeft, upperNode,
    rNode, SourceTailPanels.grid, SourceLogChord.cell, SourceLogRational.lower,
    RationalCandidate.lowerH]

'''
    s += 'def table : Fin 9 → Fin 8 → ℝ := !['+','.join(f'q{k}' for k in range(9))+']\n\n'
    s += f'''theorem table_paid (k : Fin 9) (j : Fin 8) : table k j ≤ panelTerm (rNode {idx}) k j := by
  fin_cases k
'''+''.join(f'  · exact q{k}_paid j\n' for k in range(9))
    s += f'''
theorem upper_lower : ({target}/10000000000 : ℝ) ≤ extendedNode RationalCandidate.lowerH {idx} := by
  have hs : ({sigma}/1000000000000 : ℝ) ≤
      (1105570288/1000000000000)*SourceLogRational.lower (4/(rNode {idx}-1)) := by
    norm_num [SourceLogRational.lower, rNode]
  have h := certificate (i := {idx}) (by omega) (by omega) hs table_paid
  norm_num [table, Fin.sum_univ_succ, '''+','.join(f'q{k}' for k in range(9))+'''] at h
  linarith only [h]

'''+f'''end WuPaper.R2Xi.SourceRational.Node{idx}
#print axioms WuPaper.R2Xi.SourceRational.Node{idx}.upper_lower
'''
    return target,s
if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', type=Path, metavar='DIR')
    mode.add_argument('--check', type=Path, metavar='DIR')
    args = parser.parse_args()
    targets = {}
    for i in range(11,30):
        target, source = generate(i)
        targets[i] = target
        name = f'WR2XiSourceNode{i}.lean'
        if args.write:
            args.write.mkdir(parents=True, exist_ok=True)
            (args.write/name).write_text(source)
        if args.check:
            assert (args.check/name).read_text() == source, name
    print(json.dumps({'node_lower_numerators':targets,'denominator':10**10,
                      'source_check':'passed' if args.check else 'not_requested',
                      'lean_check':'separate'},indent=2))
